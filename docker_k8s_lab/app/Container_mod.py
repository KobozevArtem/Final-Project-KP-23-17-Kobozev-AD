import ipaddress


# ==============================
# БЛОК 2. ПРОВЕРКА IP-АДРЕСА
# ==============================

def check_ip(raw_ip, trusted_ips):
    """
    Функция проверяет IP-адрес по трём условиям:
    1. IP должен быть синтаксически корректным;
    2. IP должен быть глобальным, то есть не частным и не служебным;
    3. IP должен входить в доверенный список.
    """

    # Изначально соединение считается запрещённым.
    final_flag = False

    try:
        # Преобразуем строку raw_ip в объект IP-адреса.
        # Если строка некорректная, будет вызвано исключение ValueError.
        ip = ipaddress.ip_address(raw_ip)

    except ValueError:
        # Если IP-адрес имеет неправильный формат, соединение запрещается.
        return "Получен некорректный IP-адрес. Соединение невозможно", final_flag

    # Проверяем, является ли IP-адрес глобальным.
    # Частные, локальные, служебные и зарезервированные адреса не допускаются.
    if not ip.is_global:
        return "Соединение невозможно! IP-адрес не является глобальным", final_flag

    # Проверяем принадлежность IP-адреса доверенному списку.
    # Если адрес глобальный, но не доверенный, соединение запрещается.
    if ip not in trusted_ips:
        return "Соединение невозможно! IP-адрес не является доверенным", final_flag

    # Если все проверки пройдены, соединение по IP разрешается.
    final_flag = True

    return "IP-адрес является валидным, глобальным и доверенным", final_flag


# ==============================
# БЛОК 3. ПРОВЕРКА URL И HTTPS
# ==============================

def check_https(url):
    """
    Функция проверяет URL-адрес.
    Основное требование: соединение должно выполняться через HTTPS.
    """

    # Проверяем, что URL является непустой строкой.
    if not isinstance(url, str) or not url:
        return "Некорректный URL. Соединение невозможно", False

    # Если URL начинается с https://, соединение считается безопасным.
    if url.startswith("https://"):
        return "Используется защищённый протокол HTTPS", True

    # Если используется http://, соединение запрещается как небезопасное.
    if url.startswith("http://"):
        return "Соединение невозможно! Используется небезопасный протокол HTTP", False

    # Если схема URL не указана или указана неверно, соединение запрещается.
    return "Некорректная схема URL. Требуется HTTPS", False


# ==============================
# БЛОК 4. ИТОГОВАЯ ПРОВЕРКА СОЕДИНЕНИЯ
# ==============================

def final_check(url, raw_ip, trusted_ips):
    """
    Итоговая функция проверки соединения.
    Сначала проверяется IP-адрес, затем URL и HTTPS.
    Соединение разрешается только при успешном прохождении обеих проверок.
    """

    # Выполняем проверку IP-адреса.
    ip_message, ip_permission = check_ip(raw_ip, trusted_ips)

    # Если IP не прошёл проверку, дальнейшая проверка URL не выполняется.
    if not ip_permission:
        return ip_message, False

    # Выполняем проверку URL и HTTPS.
    url_message, url_permission = check_https(url)

    # Если URL не прошёл проверку, соединение запрещается.
    if not url_permission:
        return url_message, False

    # Если IP доверенный и используется HTTPS, соединение разрешается.
    return "Соединение разрешено: IP доверенный, используется HTTPS", True
